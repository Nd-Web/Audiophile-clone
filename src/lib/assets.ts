/**
 * Helper function to get responsive image source
 * @param images - Object with desktop, tablet, mobile keys
 * @param breakpoint - Current breakpoint ('desktop' | 'tablet' | 'mobile')
 * @returns Image path for the given breakpoint
 */
export const getResponsiveImage = (
  images: { desktop?: string; tablet?: string; mobile?: string },
  breakpoint: 'desktop' | 'tablet' | 'mobile' = 'desktop'
): string => {
  return images[breakpoint] || images.desktop || '';
};

/**
 * Helper to map device viewport to breakpoint
 * @param width - Viewport width in pixels
 * @returns Breakpoint ('desktop' | 'tablet' | 'mobile')
 */
export const getBreakpointFromWidth = (width: number): 'desktop' | 'tablet' | 'mobile' => {
  if (width < 768) return 'mobile';
  if (width < 1024) return 'tablet';
  return 'desktop';
};
